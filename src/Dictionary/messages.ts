export type Messages = typeof en;

export function useMessages() {
  const locale = useAppSelector((state) => state.preferences.locale);
  return { locale, m: locale === "fa" ? fa : en };
}

export function categoryLabel(category: string, m: Messages, detailed = false) {
  switch (category) {
    case "electronics":
      return m.electronics;
    case "jewelery":
      return m.jewelry;
    case "men's clothing":
      return detailed ? m.menswear : m.apparel;
    case "women's clothing":
      return detailed ? m.womenswear : m.apparel;
    default:
      return category;
  }
}
